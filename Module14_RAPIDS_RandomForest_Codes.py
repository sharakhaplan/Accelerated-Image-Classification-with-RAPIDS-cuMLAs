import time
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import sklearn
import cuml
import cupy as cp

from sklearn.datasets import fetch_openml
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix
from cuml.ensemble import RandomForestClassifier as cuRandomForestClassifier

SEED = 42
print("scikit-learn:", sklearn.__version__)
print("cuML:", cuml.__version__)
print("GPU:", cp.cuda.runtime.getDeviceProperties(0)["name"].decode())

mnist = fetch_openml("mnist_784", version=1, as_frame=False)
X = mnist.data.astype(np.float32)
y = mnist.target.astype(np.int32)

# Piksel değerleri 0–255 aralığında; 0–1 aralığına ölçekliyoruz.
X /= 255.0

print("X şekli (örnek, özellik):", X.shape)
print("y şekli:", y.shape)
print("Sınıflar:", np.unique(y))
print("Örnek sayısı:", len(y))

fig, axes = plt.subplots(2, 5, figsize=(10, 4))
for i, ax in enumerate(axes.ravel()):
    ax.imshow(X[i].reshape(28, 28), cmap="gray")
    ax.set_title(f"Etiket: {y[i]}")
    ax.axis("off")
plt.tight_layout()
plt.show()

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=1/7, random_state=SEED, stratify=y
)

# MNIST 70.000 örnek içerdiği için bu oran yaklaşık 60.000/10.000 ayırır.
print("Eğitim:", X_train.shape, y_train.shape)
print("Test:", X_test.shape, y_test.shape)

N_TREES = 100
MAX_DEPTH = 20

cpu_model = RandomForestClassifier(
    n_estimators=N_TREES,
    max_depth=MAX_DEPTH,
    random_state=SEED,
    n_jobs=-1
)

start = time.perf_counter()
cpu_model.fit(X_train, y_train)
cpu_train_seconds = time.perf_counter() - start

cpu_pred = cpu_model.predict(X_test)
cpu_accuracy = accuracy_score(y_test, cpu_pred)

print(f"CPU eğitim süresi: {cpu_train_seconds:.2f} saniye")
print(f"CPU test accuracy: {cpu_accuracy:.4f} ({cpu_accuracy*100:.2f}%)")

# GPU verisini eğitim süresini ölçmeden önce GPU belleğine taşıyoruz.
# Böylece ölçülen süre, veri transferini değil modelin fit işlemini temsil eder.
X_train_gpu = cp.asarray(X_train, dtype=cp.float32)
y_train_gpu = cp.asarray(y_train, dtype=cp.int32)
X_test_gpu = cp.asarray(X_test, dtype=cp.float32)

# GPU verisi hazırlanırken oluşan işlemleri bitir.
cp.cuda.Stream.null.synchronize()

gpu_model = cuRandomForestClassifier(
    n_estimators=N_TREES,
    max_depth=MAX_DEPTH,
    n_bins=128,
    random_state=SEED,
    n_streams=1,
    output_type="numpy"
)

cp.cuda.Stream.null.synchronize()
start = time.perf_counter()
gpu_model.fit(X_train_gpu, y_train_gpu)
cp.cuda.Stream.null.synchronize()
gpu_train_seconds = time.perf_counter() - start

gpu_pred = np.asarray(gpu_model.predict(X_test_gpu)).astype(np.int32).ravel()
gpu_accuracy = accuracy_score(y_test, gpu_pred)

print(f"GPU eğitim süresi (veri GPU belleğine önceden aktarılmıştır): {gpu_train_seconds:.2f} saniye")
print(f"GPU test accuracy: {gpu_accuracy:.4f} ({gpu_accuracy*100:.2f}%)")

results = pd.DataFrame({
    "Model": ["scikit-learn Random Forest (CPU)", "RAPIDS cuML Random Forest (GPU)"],
    "Eğitim süresi (saniye)": [cpu_train_seconds, gpu_train_seconds],
    "Test accuracy": [cpu_accuracy, gpu_accuracy],
    "Test accuracy (%)": [cpu_accuracy * 100, gpu_accuracy * 100],
})
display(results.round(4))

speedup = cpu_train_seconds / gpu_train_seconds if gpu_train_seconds > 0 else np.nan
print(f"Eğitim süresi hızlanma oranı (CPU/GPU): {speedup:.2f}x")
print(f"Accuracy farkı (GPU - CPU): {(gpu_accuracy - cpu_accuracy)*100:.3f} yüzde puan")

plt.figure(figsize=(7, 4))
plt.bar(["scikit-learn CPU", "cuML GPU"], [cpu_train_seconds, gpu_train_seconds])
plt.ylabel("Eğitim süresi (saniye)")
plt.title("Random Forest eğitim süresi karşılaştırması")
plt.tight_layout()
plt.show()

plt.figure(figsize=(7, 4))
plt.bar(["scikit-learn CPU", "cuML GPU"], [cpu_accuracy * 100, gpu_accuracy * 100])
plt.ylabel("Test accuracy (%)")
plt.ylim(0, 100)
plt.title("Test doğruluğu karşılaştırması")
plt.tight_layout()
plt.show()

print("CPU sınıflandırma raporu:")
print(classification_report(y_test, cpu_pred, digits=4))

print("GPU sınıflandırma raporu:")
print(classification_report(y_test, gpu_pred, digits=4))

fig, axes = plt.subplots(1, 2, figsize=(12, 5))
for ax, pred, title in [
    (axes[0], cpu_pred, "scikit-learn CPU"),
    (axes[1], gpu_pred, "cuML GPU")
]:
    cm = confusion_matrix(y_test, pred, labels=np.arange(10))
    im = ax.imshow(cm, cmap="Blues")
    ax.set_title(title)
    ax.set_xlabel("Tahmin edilen sınıf")
    ax.set_ylabel("Gerçek sınıf")
    ax.set_xticks(range(10))
    ax.set_yticks(range(10))
plt.tight_layout()
plt.show()
